/* =========================================================
   HELPER FUNCTIONS
========================================================= */

window.ELITE_BAGS.getProduct = function(id){
  return this.products.find(function(product){
    return product.id === String(id);
  });
};

window.ELITE_BAGS.getCategory = function(category){
  return this.products.filter(function(product){
    return product.category.toLowerCase() === category.toLowerCase();
  });
};

window.ELITE_BAGS.search = function(query){
  var q = String(query || "").trim().toLowerCase();

  if(!q){
    return this.products;
  }

  return this.products.filter(function(product){
    return [
      product.id,
      product.name,
      product.category,
      product.subcategory,
      product.colors.join(" "),
      product.material,
      product.description
    ].join(" ").toLowerCase().includes(q);
  });
};
